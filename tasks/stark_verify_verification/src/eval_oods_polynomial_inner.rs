// Compute constraints - split into 10 parts, each processing ~20 constraints
// Using helper function to minimize stack usage

#[inline(never)]
fn compute_constraints_part1<T: BidirectionalStack + ProofData + ProofDataVerification>(
    obj: &mut EvalOodsPolynomialInner,
    stack: &mut T,
) -> Vec<Vec<u8>> {
    let (autogenerated_pows, oods_values, constraint_coefficients, column_values) =
        stack.get_proof_data_references::<StarkProof>();
    let mut total_sum = FELT_0;

    // Constraints 0-19: column0 and column1
    let column0 = &column_values[0];
    let column1 = &column_values[1];

    // Constraints 0-15 (column0)
    for (i, pow_idx) in [
        (0, 0),
        (1, 4),
        (2, 5),
        (3, 6),
        (4, 7),
        (5, 8),
        (6, 9),
        (7, 10),
        (8, 11),
        (9, 13),
        (10, 14),
        (11, 15),
        (12, 16),
        (13, 17),
        (14, 18),
        (15, 19),
    ] {
        total_sum += compute_single_constraint(
            column0,
            &oods_values[i],
            &obj.point,
            &autogenerated_pows[pow_idx],
            &obj.oods_point,
            &constraint_coefficients[i],
        );
    }

    // Constraints 16-19 (column1)
    for (i, pow_idx) in [(16, 0), (17, 4), (18, 5), (19, 6)] {
        total_sum += compute_single_constraint(
            column1,
            &oods_values[i],
            &obj.point,
            &autogenerated_pows[pow_idx],
            &obj.oods_point,
            &constraint_coefficients[i],
        );
    }

    obj.total_sum = total_sum;
    obj.phase = EvalOodsPolynomialInnerPhase::ComputeConstraintsPart2;
    vec![]
}


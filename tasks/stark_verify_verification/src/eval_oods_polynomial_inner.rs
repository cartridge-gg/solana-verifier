// Helper function to compute a single constraint - ultra minimal stack usage
#[inline(never)]
fn compute_single_constraint(
    column_value: &Felt,
    oods_value: &Felt,
    point: &Felt,
    autogenerated_pow: &Felt,
    oods_point: &Felt,
    constraint_coeff: &Felt,
) -> Felt {
    let numerator = column_value - oods_value;
    let temp = autogenerated_pow * oods_point;
    let denominator = point - temp;
    let value = numerator.field_div(&felt_nonzero!(denominator));
    constraint_coeff * value
}

// Helper function for composition polynomial constraints
#[inline(never)]
fn compute_composition_constraint(
    column_value: &Felt,
    oods_value: &Felt,
    point: &Felt,
    oods_point_to_deg: &Felt,
    constraint_coeff: &Felt,
) -> Felt {
    let numerator = column_value - oods_value;
    let denominator = point - oods_point_to_deg;
    let value = numerator.field_div(&felt_nonzero!(denominator));
    constraint_coeff * value
}

// Compute powers - split into 9 parts with max ~15 operations each for minimal stack usage
#[inline(never)]
fn compute_powers1<T: BidirectionalStack + ProofData + ProofDataVerification>(
    obj: &mut EvalOodsPolynomialInner,
    stack: &mut T,
) -> Vec<Vec<u8>> {
    obj.point = Felt::from_bytes_be_slice(stack.borrow_front());
    stack.pop_front();
    obj.oods_point = Felt::from_bytes_be_slice(stack.borrow_front());
    stack.pop_front();
    obj.trace_generator = Felt::from_bytes_be_slice(stack.borrow_front());
    stack.pop_front();

    let autogenerated_pows = stack.get_autogenerated_pows_mut();
    // Initial powers from pow_felt
    autogenerated_pows[0] = obj.trace_generator.pow_felt(&(FELT_0));
    autogenerated_pows[1] = obj.trace_generator.pow_felt(&(FELT_4089));
    autogenerated_pows[2] = obj.trace_generator.pow_felt(&(FELT_2011));
    autogenerated_pows[3] = obj.trace_generator.pow_felt(&(FELT_1539));
    autogenerated_pows[4] = obj.trace_generator.pow_felt(&(FELT_1));

    // Indices 5-14 (10 operations)
    let temp = autogenerated_pows[4];
    autogenerated_pows[5] = temp * temp;
    autogenerated_pows[6] = autogenerated_pows[4] * autogenerated_pows[5];
    autogenerated_pows[7] = autogenerated_pows[4] * autogenerated_pows[6];
    autogenerated_pows[8] = autogenerated_pows[4] * autogenerated_pows[7];
    autogenerated_pows[9] = autogenerated_pows[4] * autogenerated_pows[8];
    autogenerated_pows[10] = autogenerated_pows[4] * autogenerated_pows[9];
    autogenerated_pows[11] = autogenerated_pows[4] * autogenerated_pows[10];
    autogenerated_pows[12] = autogenerated_pows[3] * autogenerated_pows[11];
    autogenerated_pows[13] = autogenerated_pows[4] * autogenerated_pows[11];
    autogenerated_pows[14] = autogenerated_pows[4] * autogenerated_pows[13];

    obj.phase = EvalOodsPolynomialInnerPhase::ComputePowers2;
    vec![]
}

